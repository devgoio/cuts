import AppKit
import CryptoKit
import ImageIO

enum ClipboardKind: String, Codable {
    case text, image, files
}

struct ClipboardRecord: Codable, Identifiable {
    let id: UUID
    var capturedAt: Date
    let kind: ClipboardKind
    let fingerprint: String
    let title: String
    let text: String?
    let filePaths: [String]?
    let imageType: String?
    let byteCount: Int
}

@MainActor
final class ClipboardArchive {
    static let maxRecords = 50
    static let maxFavorites = 10
    nonisolated static let maxTotalBytes = 200 * 1024 * 1024
    static let maxImageBytes = 64 * 1024 * 1024
    static let maxTextBytes = 1024 * 1024

    let directory: URL
    private(set) var records: [ClipboardRecord] = []
    private(set) var favorites: [ClipboardRecord] = []
    var onThumbnail: ((UUID) -> Void)?
    private let thumbnailQueue = DispatchQueue(label: "com.psn.Cuts.clipboardThumbs", qos: .utility)
    private let fileManager = FileManager.default
    private let byteBudget: Int

    init(directory: URL? = nil, byteBudget: Int = ClipboardArchive.maxTotalBytes) {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? FileManager.default.temporaryDirectory
        self.directory = directory ?? support.appendingPathComponent("PsnAppRebuild/Clipboard", isDirectory: true)
        self.byteBudget = byteBudget
        try? fileManager.createDirectory(at: self.directory, withIntermediateDirectories: true)
        load()
    }

    @discardableResult
    func capture(_ pasteboard: NSPasteboard) -> ClipboardRecord? {
        let hiddenTypes: Set<NSPasteboard.PasteboardType> = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        ]
        if pasteboard.types?.contains(where: { hiddenTypes.contains($0) }) == true { return nil }

        let paths = FileClipboard.paths(in: pasteboard)
        if !paths.isEmpty { return addFiles(paths) }

        for type in [NSPasteboard.PasteboardType.png, NSPasteboard.PasteboardType("public.jpeg"), .tiff] {
            guard pasteboard.types?.contains(type) == true,
                  let data = pasteboard.data(forType: type), !data.isEmpty else { continue }
            return addImage(data, type: type.rawValue)
        }

        if let text = pasteboard.string(forType: .string), !text.isEmpty { return addText(text) }
        return nil
    }

    @discardableResult
    func addText(_ text: String) -> ClipboardRecord? {
        let size = text.utf8.count
        guard size > 0, size <= Self.maxTextBytes else {
            if size > 0 { CutsLog.write(.warning, "clipboard", "text exceeds history size limit") }
            return nil
        }
        let fingerprint = digest(Data(text.utf8), prefix: "text")
        if let existing = promote(fingerprint: fingerprint) { return existing }
        let title = String(text.replacingOccurrences(of: "\n", with: " ").prefix(180))
        let record = ClipboardRecord(id: UUID(), capturedAt: Date(), kind: .text,
                                     fingerprint: fingerprint, title: title, text: text,
                                     filePaths: nil, imageType: nil, byteCount: size)
        return insert(record) ? record : nil
    }

    @discardableResult
    func addFiles(_ paths: [String]) -> ClipboardRecord? {
        let normalized = paths.filter { !$0.isEmpty }
        guard !normalized.isEmpty else { return nil }
        let size = normalized.reduce(0) { $0 + $1.utf8.count }
        guard size <= Self.maxTextBytes else { return nil }
        let fingerprint = digest(Data(normalized.joined(separator: "\u{0}").utf8), prefix: "files")
        if let existing = promote(fingerprint: fingerprint) { return existing }
        let name = URL(fileURLWithPath: normalized[0]).lastPathComponent
        let title = normalized.count == 1 ? name : "\(name) 等 \(normalized.count) 个文件"
        let record = ClipboardRecord(id: UUID(), capturedAt: Date(), kind: .files,
                                     fingerprint: fingerprint, title: title, text: nil,
                                     filePaths: normalized, imageType: nil, byteCount: size)
        return insert(record) ? record : nil
    }

    @discardableResult
    func addImage(_ data: Data, type: String) -> ClipboardRecord? {
        guard !data.isEmpty, data.count <= Self.maxImageBytes else {
            if !data.isEmpty { CutsLog.write(.warning, "clipboard", "image exceeds history size limit") }
            return nil
        }
        guard [NSPasteboard.PasteboardType.png.rawValue, "public.jpeg", NSPasteboard.PasteboardType.tiff.rawValue].contains(type) else { return nil }
        let fingerprint = digest(data, prefix: "image")
        if let existing = promote(fingerprint: fingerprint) { return existing }
        let id = UUID()
        let record = ClipboardRecord(id: id, capturedAt: Date(), kind: .image,
                                     fingerprint: fingerprint, title: "图片 · \(ByteCountFormatter.string(fromByteCount: Int64(data.count), countStyle: .file))",
                                     text: nil, filePaths: nil, imageType: type, byteCount: data.count)
        do {
            try data.write(to: imageURL(for: record), options: .atomic)
            guard insert(record) else {
                removeBlobs(for: record)
                return nil
            }
            scheduleThumbnail(for: record)
            return record
        } catch {
            CutsLog.failure("clipboard", "store image", error)
            return nil
        }
    }

    func restore(_ record: ClipboardRecord, to pasteboard: NSPasteboard) -> Bool {
        switch record.kind {
        case .text:
            guard let text = record.text else { return false }
            pasteboard.clearContents()
            return pasteboard.setString(text, forType: .string)
        case .files:
            let paths = record.filePaths ?? []
            guard paths.allSatisfy({ fileManager.fileExists(atPath: $0) }) else { return false }
            return FileClipboard.write(paths, to: pasteboard)
        case .image:
            guard let type = record.imageType, let data = try? Data(contentsOf: imageURL(for: record)) else { return false }
            pasteboard.clearContents()
            return pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
        }
    }

    func thumbnailURL(for record: ClipboardRecord) -> URL {
        directory.appendingPathComponent(record.id.uuidString + ".preview.jpg")
    }

    func previewSource(for record: ClipboardRecord) -> URL? {
        record.kind == .image ? imageURL(for: record) : nil
    }

    func originalImage(for record: ClipboardRecord) -> CGImage? {
        previewSource(for: record).flatMap { try? ClipboardImageReader.decode($0) }
    }

    func isFavorite(_ record: ClipboardRecord) -> Bool { favorites.contains { $0.id == record.id } }

    @discardableResult
    func toggleFavorite(_ record: ClipboardRecord) -> Bool {
        var updated = favorites
        var removed: [ClipboardRecord] = []
        if let index = updated.firstIndex(where: { $0.id == record.id }) {
            removed.append(updated.remove(at: index))
        } else {
            guard records.contains(where: { $0.id == record.id }) else { return false }
            updated.insert(record, at: 0)
            if updated.count > Self.maxFavorites { removed.append(updated.removeLast()) }
        }
        guard writeIndex(updated, file: "favorites.json") else { return false }
        favorites = updated
        removed.forEach(removeUnusedBlobs)
        return true
    }

    @discardableResult
    func delete(_ record: ClipboardRecord) -> Bool {
        guard let index = records.firstIndex(where: { $0.id == record.id }) else { return false }
        var updated = records
        let removed = updated.remove(at: index)
        guard writeIndex(updated, file: "index.json") else { return false }
        records = updated
        removeUnusedBlobs(for: removed)
        return true
    }

    private func insert(_ record: ClipboardRecord) -> Bool {
        let favoriteIDs = Set(favorites.map(\.id))
        let reserved = favorites.reduce(0) { $0 + $1.byteCount }
        // Pre-existing favorites are not deleted to meet the new shared budget.
        let limit = reserved > byteBudget ? reserved + Self.maxTextBytes : byteBudget
        if !favoriteIDs.contains(record.id), record.byteCount > limit - reserved {
            CutsLog.write(.warning, "clipboard", "history item exceeds available archive budget")
            return false
        }
        return pruneAndPersist([record] + records.filter { $0.id != record.id }, reserved: reserved,
                               favoriteIDs: favoriteIDs, limit: limit)
    }

    private func promote(fingerprint: String) -> ClipboardRecord? {
        guard let existing = records.first(where: { $0.fingerprint == fingerprint })
            ?? favorites.first(where: { $0.fingerprint == fingerprint }) else { return nil }
        var updated = existing
        updated.capturedAt = Date()
        return insert(updated) ? updated : existing
    }

    @discardableResult
    private func pruneAndPersist(_ proposed: [ClipboardRecord], reserved: Int = 0,
                                 favoriteIDs: Set<UUID> = [], limit: Int) -> Bool {
        var updated = proposed
        var total = reserved + updated.reduce(0) { $0 + (favoriteIDs.contains($1.id) ? 0 : $1.byteCount) }
        var expired: [ClipboardRecord] = []
        while updated.count > Self.maxRecords || total > limit {
            guard !updated.isEmpty else { return false }
            let index: Int
            if updated.count > Self.maxRecords { index = updated.count - 1 }
            else if let oldest = updated.lastIndex(where: { !favoriteIDs.contains($0.id) }) { index = oldest }
            else { return false }
            let removed = updated.remove(at: index)
            if !favoriteIDs.contains(removed.id) { total -= removed.byteCount }
            expired.append(removed)
        }
        guard writeIndex(updated, file: "index.json") else { return false }
        records = updated
        expired.forEach(removeUnusedBlobs)
        return true
    }

    private func removeUnusedBlobs(for record: ClipboardRecord) {
        guard !isFavorite(record), !records.contains(where: { $0.id == record.id }) else { return }
        removeBlobs(for: record)
    }

    private func removeBlobs(for record: ClipboardRecord) {
        guard record.kind == .image else { return }
        try? fileManager.removeItem(at: imageURL(for: record))
        try? fileManager.removeItem(at: thumbnailURL(for: record))
    }

    private func imageURL(for record: ClipboardRecord) -> URL {
        let ext = record.imageType == "public.jpeg" ? "jpg"
            : record.imageType == NSPasteboard.PasteboardType.tiff.rawValue ? "tiff" : "png"
        return directory.appendingPathComponent(record.id.uuidString + "." + ext)
    }

    private func scheduleThumbnail(for record: ClipboardRecord) {
        let source = imageURL(for: record)
        let target = thumbnailURL(for: record)
        thumbnailQueue.async { [weak self] in
            guard let thumbnail = ClipboardImageReader.thumbnail(source) else { return }
            DispatchQueue.main.async { [weak self] in
                guard let self, self.isFavorite(record) || self.records.contains(where: { $0.id == record.id }),
                      self.fileManager.fileExists(atPath: source.path) else { return }
                do {
                    try thumbnail.write(to: target, options: .atomic)
                    self.onThumbnail?(record.id)
                } catch { CutsLog.failure("clipboard", "cache thumbnail", error) }
            }
        }
    }

    private func digest(_ data: Data, prefix: String) -> String {
        let hash = SHA256.hash(data: data)
        return prefix + ":" + hash.map { String(format: "%02x", $0) }.joined()
    }

    private func writeIndex(_ records: [ClipboardRecord], file: String) -> Bool {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        do {
            let data = try encoder.encode(records)
            try data.write(to: directory.appendingPathComponent(file), options: .atomic)
            return true
        } catch {
            CutsLog.write(.warning, "clipboard", "could not save clipboard index")
            return false
        }
    }

    private func load() {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        func read(_ file: String) -> [ClipboardRecord]? {
            let url = directory.appendingPathComponent(file)
            guard let data = try? Data(contentsOf: url),
                  let decoded = try? decoder.decode([ClipboardRecord].self, from: data) else { return nil }
            return decoded.filter { $0.kind != .image || fileManager.fileExists(atPath: imageURL(for: $0).path) }
        }
        let savedFavorites = read("favorites.json") ?? []
        favorites = Array(savedFavorites.prefix(Self.maxFavorites))
        if let history = read("index.json") {
            records = history
            if records.count > Self.maxRecords || records.reduce(0, { $0 + $1.byteCount }) > byteBudget {
                pruneAndPersist(records, limit: byteBudget)
            }
        }
        if savedFavorites.count > favorites.count, writeIndex(favorites, file: "favorites.json") {
            savedFavorites.dropFirst(Self.maxFavorites).forEach(removeUnusedBlobs)
        }
    }

    static func verifyTemporaryArchive() -> Bool {
        guard ClipboardImageReader.withinBudget(width: 10_240, height: 2_880),
              !ClipboardImageReader.withinBudget(width: 8_000, height: 8_000),
              !ClipboardImageReader.withinBudget(width: Int.max, height: Int.max),
              !ClipboardImageReader.withinBudget(width: 10, height: 0) else { return false }
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("psn-rebuild-test-" + UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let archive = ClipboardArchive(directory: directory)
        guard archive.addText("历史文字") != nil,
              archive.addFiles(["/tmp/example-a", "/tmp/example-b"]) != nil,
              archive.addText("历史文字") != nil,
              archive.records.count == 2,
              archive.records[0].kind == .text else { return false }
        let reopened = ClipboardArchive(directory: directory)
        guard reopened.records.count == 2,
              reopened.records[0].text == "历史文字",
              reopened.records[1].filePaths?.count == 2 else { return false }
        let context = CGContext(data: nil, width: 2, height: 2, bitsPerComponent: 8, bytesPerRow: 8,
                                space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
        guard let image = context?.makeImage(),
              let png = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]),
              let entry = reopened.addImage(png, type: NSPasteboard.PasteboardType.png.rawValue),
              let original = reopened.originalImage(for: entry), original.width == 2, original.height == 2,
              let saved = try? Data(contentsOf: reopened.imageURL(for: entry)),
              saved == png else { return false }
        guard reopened.delete(entry), reopened.records.count == 2,
              !FileManager.default.fileExists(atPath: reopened.thumbnailURL(for: entry).path),
              let protected = reopened.addImage(png, type: NSPasteboard.PasteboardType.png.rawValue),
              reopened.toggleFavorite(protected), reopened.delete(protected),
              reopened.originalImage(for: protected) != nil,
              ClipboardArchive(directory: directory).isFavorite(protected) else { return false }
        for index in 1...55 { reopened.addText("History \(index)") }
        guard reopened.records.count == Self.maxRecords, reopened.records.last?.text == "History 6",
              reopened.favorites.first?.id == protected.id, reopened.records.allSatisfy({ $0.id != protected.id }),
              let source = reopened.previewSource(for: protected),
              (try? Data(contentsOf: source)) == png else { return false }
        let persisted = ClipboardArchive(directory: directory)
        guard persisted.favorites.first?.id == protected.id, persisted.records.count == Self.maxRecords,
              persisted.addImage(png, type: NSPasteboard.PasteboardType.png.rawValue)?.id == protected.id else { return false }
        // Pushing the oldest favorite out must not remove an image still in history.
        for record in Array(persisted.records.dropFirst().prefix(Self.maxFavorites)) {
            guard persisted.toggleFavorite(record) else { return false }
        }
        guard persisted.favorites.count == Self.maxFavorites, !persisted.isFavorite(protected),
              FileManager.default.fileExists(atPath: source.path) else { return false }
        for index in 1...50 { persisted.addText("New \(index)") }
        let final = ClipboardArchive(directory: directory)
        guard final.records.count == Self.maxRecords && final.favorites.count == Self.maxFavorites
            && final.records.last?.text == "New 1"
            && !FileManager.default.fileExists(atPath: source.path) else { return false }
        let small = ClipboardArchive(directory: directory.appendingPathComponent("budget"), byteBudget: 12)
        guard let favorite = small.addText("12345"), small.toggleFavorite(favorite), small.delete(favorite),
              small.addText("abcd") != nil, small.addText("qrst") != nil,
              small.addText("oversized") == nil else { return false }
        return small.favorites.count == 1 && small.records.map(\.text) == ["qrst"]
            && verifyFileClipboard(in: directory)
    }

    private static func verifyFileClipboard(in directory: URL) -> Bool {
        let file = directory.appendingPathComponent("样例 A.xlsx")
        let other = directory.appendingPathComponent("Sample B.xlsx")
        do {
            try Data([0]).write(to: file)
            try Data([0]).write(to: other)
        } catch { return false }
        let urls = [file, other].map { $0.standardizedFileURL }
        let expected = urls.map(\.path)
        let archive = ClipboardArchive(directory: directory.appendingPathComponent("file-roundtrip"))
        let source = NSPasteboard.withUniqueName()
        let output = NSPasteboard.withUniqueName()
        defer { source.releaseGlobally(); output.releaseGlobally() }

        guard source.setPropertyList(expected, forType: FileClipboard.filenameList),
              let fromLegacy = archive.capture(source), fromLegacy.kind == .files,
              fromLegacy.filePaths == expected,
              archive.restore(fromLegacy, to: output),
              FileClipboard.paths(in: output) == expected,
              output.propertyList(forType: FileClipboard.filenameList) as? [String] == expected,
              output.pasteboardItems?.map({ $0.string(forType: .fileURL) }) == urls.map({ Optional($0.absoluteString) }) else {
            print("clipboard file URL / legacy list roundtrip failed")
            return false
        }
        source.clearContents()
        guard source.writeObjects(urls.map { $0 as NSURL }),
              archive.capture(source)?.id == fromLegacy.id else { return false }
        source.clearContents()
        let hidden = NSPasteboardItem()
        hidden.setString(urls[0].absoluteString, forType: .fileURL)
        hidden.setString("1", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        return source.writeObjects([hidden]) && archive.capture(source) == nil
    }
}

@MainActor
final class ClipboardMonitor {
    let archive: ClipboardArchive
    var onChange: (() -> Void)?
    private var lastChangeCount: Int
    private var timer: Timer?

    init(archive: ClipboardArchive) {
        self.archive = archive
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer.tolerance = 0.04
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func noteOwnWrite(_ changeCount: Int) { lastChangeCount = changeCount }
    func captureLatest() { poll() }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        if archive.capture(pasteboard) != nil { onChange?() }
    }

    deinit { timer?.invalidate() }
}
